"""Test script for continuing a paused run with AGUI protocol

This script tests the full AGUI protocol continuation flow after a tool requires confirmation:
1. Start a run through AGUI router that pauses for confirmation
2. Get the StateSnapshotEvent with tools to confirm  
3. Mark tools as confirmed
4. Continue the run through AGUI router with confirmed tools

This tests the complete AGUI router flow, ensuring that runs are properly 
saved to the database and can be continued after pausing.

Run with: uv run cookbook/agent_os/interfaces/agui/test_continue_run.py

Note: On Windows, you may see an "Event loop is closed" warning at the end.
This is a harmless asyncio cleanup warning and doesn't affect test results.
"""

import asyncio
import tempfile

from agno.agent.agent import Agent
from agno.models.openai import OpenAIChat
from agno.tools import tool
from agno.db.sqlite import SqliteDb
from ag_ui.core import RunAgentInput, EventType
from agno.os.interfaces.agui.router import run_agent
from agno.models.response import ToolExecution

